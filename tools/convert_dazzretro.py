"""Convert the retro-camera LUTs of ganjmeng/dazz-retro-camera into app LUT assets.

The project (MIT) is an open retro / CCD camera app in the manner of the "Dazz" style
cameras. Its camera LUTs are generated by its own scripts (generate_camera_luts.py and
fix_luts_v2.py: channel gains, gamma, temperature, contrast, saturation per camera),
not taken from another app. Each .cube (sRGB in and out, 33^3) is resampled to the
engine's 33^3 RGB8 layout (red fastest).

The entries go after the other leading LUTs (CCD cameras, Editor Hub) and ahead of the
film LUTs; the manifest's "leading" count says how many lead the films (stored LUT
choices of film LUTs shift by it).

    python tools/convert_dazzretro.py [path]   (default third_party/dazz-retro)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from convert_editorhub import OUT, read_cube, resample  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "third_party" / "dazz-retro"

CCD = "复古相机 · 数码"
FILM = "复古相机 · 胶片机"
INSTANT = "复古相机 · 拍立得"
MONO = "复古相机 · 黑白"
# file stem -> (group, label)
LUTS = {
    "ccd_r": (CCD, "CCD R · 早期 CCD 冷调"),
    "ccd_m": (CCD, "CCD M · CCD 卡片机"),
    "d_classic": (CCD, "D Classic · 2000 年代暖调直出"),
    "grd_r": (CCD, "GRD R · 冷中性街拍"),
    "fxn_r": (CCD, "FXN R · 2010 CMOS 清冷"),
    "fxnr_33": (CCD, "FXN R · 冷青"),
    "cpm35_kodak_colorplus": (FILM, "CPM35 · ColorPlus 200"),
    "cpm35_kodak_gold_warm": (FILM, "CPM35 · Gold 200 暖调"),
    "cpm35_kodak_portrait": (FILM, "CPM35 · Gold 人像"),
    "cpm35_kodak_warm_clean": (FILM, "CPM35 · 暖调干净"),
    "fqs_fuji_portra": (FILM, "FQS · Superia + Portra"),
    "fqs_superia400_flash": (FILM, "FQS · Superia 400 闪光"),
    "fqs_superia400_indoor": (FILM, "FQS · Superia 400 室内"),
    "fqs_superia400_natural": (FILM, "FQS · Superia 400 日光"),
    "u300": (FILM, "U300 · 一次性相机"),
    "u300_color": (FILM, "U300 · Color 400"),
    "u300_gold": (FILM, "U300 · Gold 200"),
    "u300_portra": (FILM, "U300 · Portra"),
    "fisheye": (FILM, "Fisheye · LOMO 鱼眼"),
    "inst_c": (INSTANT, "Inst C · Mini 暖粉"),
    "inst_c_polaroid_warm": (INSTANT, "Inst C · 600 暖调"),
    "inst_s": (INSTANT, "Inst S · 柔和人像"),
    "inst_sq": (INSTANT, "Inst SQ · 方形"),
    "inst_sqc_warm": (INSTANT, "Inst SQC · 方形暖调"),
    "bw_hp5": (MONO, "BW · HP5"),
    "bw_trix400": (MONO, "BW · Tri-X 400"),
}
GROUPS = {CCD, FILM, INSTANT, MONO}
LEADING = ("digicam/", "editorhub/")


def main():
    (OUT / "retro").mkdir(parents=True, exist_ok=True)
    entries = []
    for stem, (group, label) in LUTS.items():
        data = resample(*read_cube(SOURCE / "cube" / f"{stem}.cube"))
        (OUT / "retro" / f"{stem}.rgb").write_bytes(data.tobytes())
        entries.append({"id": f"retro/{stem}", "label": label, "group": group})
    (OUT / "retro" / "LICENSE").write_text(
        "Retro camera LUTs from https://github.com/ganjmeng/dazz-retro-camera\n"
        "(flutter_app/assets/lut/cameras), MIT License, Copyright (c) 2026 DAZZ Team.\n"
        "Converted to 33^3 RGB8 by tools/convert_dazzretro.py; the full license text is in\n"
        "third_party/dazz-retro/LICENSE.\n", encoding="utf-8")
    path = OUT / "manifest.json"
    manifest = json.loads(path.read_text(encoding="utf-8"))
    luts = [e for e in manifest["luts"] if e.get("group") not in GROUPS]
    lead = [e for e in luts if e["id"].startswith(LEADING)]
    rest = [e for e in luts if not e["id"].startswith(LEADING)]
    manifest["luts"] = lead + entries + rest
    manifest["leading"] = len(lead) + len(entries)
    manifest["retro_source"] = "https://github.com/ganjmeng/dazz-retro-camera, MIT"
    path.write_text(json.dumps(manifest, ensure_ascii=False), encoding="utf-8")
    print(f"{len(entries)} retro camera LUTs; {manifest['leading']} lead the films; {len(manifest['luts'])} in all")


if __name__ == "__main__":
    main()
