    fun camera(key: String) = cameras.firstOrNull { it.key == key }

    private val luts = HashMap<String, FloatArray>()

    /** The camera's LUT ([b][g][r][rgb], u16 little-endian in the asset) as floats 0..1. */
    @Synchronized private fun lut(context: Context, key: String): FloatArray = luts.getOrPut(key) {
        val bytes = context.assets.open("luts/digicam/$key.lut").use { it.readBytes() }
        FloatArray(bytes.size / 2) { i -> ((bytes[2 * i].toInt() and 0xff) or ((bytes[2 * i + 1].toInt() and 0xff) shl 8)) / 65535f }
    }

    /** White Gaussian noise, [y][x][4] signed bytes, unit spread 32 (as the emulator's tile). */
    @Volatile private var tile: ByteArray? = null
    private fun noiseTile(): ByteArray = tile ?: synchronized(this) {
        tile ?: java.util.Random(0x5eed1e).let { rnd ->
            ByteArray(NT * NT * 4) { (rnd.nextGaussian() * 32).roundToInt().coerceIn(-127, 127).toByte() }
        }.also { tile = it }
    }

    private val dec8 = FloatArray(256) { i ->
        val v = i / 255f
        if (v <= 0.04045f) v / 12.92f else Math.pow(((v + 0.055f) / 1.055f).toDouble(), 2.4).toFloat()
    }
    private const val TAB = 4096
    /** sRGB-encoded 0..1 -> linear, and linear 0..1 -> encoded, as tables (lerped). */
    private val decTab = FloatArray(TAB + 1) { i ->
        val v = i / TAB.toFloat()
        if (v <= 0.04045f) v / 12.92f else Math.pow(((v + 0.055f) / 1.055f).toDouble(), 2.4).toFloat()
    }
    private val encTab = FloatArray(TAB + 1) { i ->
        // indexed by sqrt(linear): finer steps near black, where encoding is steep
        val x = (i / TAB.toFloat()).let { it * it }
        if (x <= 0.0031308f) x * 12.92f else (1.055 * Math.pow(x.toDouble(), 1 / 2.4) - 0.055).toFloat()
    }
    private fun decode(v: Float): Float {
        val p = v.coerceIn(0f, 1f) * TAB
        val i = minOf(p.toInt(), TAB - 1)
        return decTab[i] + (decTab[i + 1] - decTab[i]) * (p - i)
    }
    private fun encode(v: Float): Float {
        val p = sqrt(v.coerceIn(0f, 1f)) * TAB
        val i = minOf(p.toInt(), TAB - 1)
        return encTab[i] + (encTab[i + 1] - encTab[i]) * (p - i)
    }

    private val invLn2 = (1 / ln(2.0)).toFloat()
    private fun log2(v: Float) = ln(maxOf(v, 1e-30f).toDouble()).toFloat() * invLn2

    // The shaper as a table over the float's exponent and top 8 mantissa bits (as the emulator's
    // build_shaper): exponents -11 .. 2 hold the LUT's 13 stops around 0.18.
    private const val SH_E0 = -11
    private const val SH_LEN = 14 * 256
    private val shTab = FloatArray(SH_LEN + 1) { k ->
        val e = SH_E0 + k / 256
        val m = 1.0 + (k % 256) / 256.0
        (((e + ln(m) / ln(2.0)).toFloat() - LOG2_018 - STOPS_LO) / (STOPS_HI - STOPS_LO) * (N - 1))
    }

    /** A linear value's LUT position (0..N-1) on the 13-stop log2 shaper. */
    private fun shaper(v: Float): Float {
        val bits = java.lang.Float.floatToRawIntBits(maxOf(v, 1e-30f))
        val k = (bits ushr 15) - ((127 + SH_E0) shl 8)
        val p = when {
            k < 0 -> 0f
            k >= SH_LEN -> (N - 1).toFloat()
            else -> {
                val f = (bits and 0x7fff) * (1f / 32768f)
                shTab[k] + (shTab[k + 1] - shTab[k]) * f
            }
        }
        return p.coerceIn(0f, (N - 1).toFloat())
    }

    /** Tetrahedral interpolation in the camera's LUT; sRGB-encoded out into [out]. */
    private fun render(lut: FloatArray, r: Float, g: Float, b: Float, out: FloatArray) {
        val pr = shaper(r); val pg = shaper(g); val pb = shaper(b)
        val ir = minOf(pr.toInt(), N - 2); val ig = minOf(pg.toInt(), N - 2); val ib = minOf(pb.toInt(), N - 2)
        val fr = pr - ir; val fg = pg - ig; val fb = pb - ib
        val a: Int; val bb: Int; val w1: Float; val w2: Float; val w3: Float
        if (fr > fg) {
            if (fg > fb) { a = DR; bb = DR + DG; w1 = fr - fg; w2 = fg - fb; w3 = fb }
            else if (fr > fb) { a = DR; bb = DR + DB; w1 = fr - fb; w2 = fb - fg; w3 = fg }
            else { a = DB; bb = DR + DB; w1 = fb - fr; w2 = fr - fg; w3 = fg }
        } else if (fb > fg) { a = DB; bb = DG + DB; w1 = fb - fg; w2 = fg - fr; w3 = fr }
        else if (fb > fr) { a = DG; bb = DG + DB; w1 = fg - fb; w2 = fb - fr; w3 = fr }
        else { a = DG; bb = DR + DG; w1 = fg - fr; w2 = fr - fb; w3 = fb }
        val w0 = 1f - (w1 + w2 + w3)
        val p0 = ib * DB + ig * DG + ir * DR
        val pa = p0 + a; val pb2 = p0 + bb; val pc = p0 + DR + DG + DB
        for (k in 0..2) out[k] = w0 * lut[p0 + k] + w1 * lut[pa + k] + w2 * lut[pb2 + k] + w3 * lut[pc + k]
    }

    // ---- blurs (common/src/blur.rs: two box passes each way, edges repeat) ----------------------

    private fun boxPass(src: FloatArray, so: Int, dst: FloatArray, dO: Int, lines: Int, len: Int, lineStep: Int, stride: Int, r: Int) {
        val inv = 1f / (2 * r + 1)
        val last = len - 1
        for (l in 0 until lines) {
            val s = so + l * lineStep
            val d = dO + l * lineStep
            var acc = 0f
            for (i in 0..2 * r) {
                val j = if (i < r) 0 else if (i - r > last) last else i - r
                acc += src[s + j * stride]
            }
            for (i in 0 until len) {
                dst[d + i * stride] = acc * inv
                val next = if (i + r < last) src[s + (i + r + 1) * stride] else src[s + last * stride]
                val prev = if (i >= r) src[s + (i - r) * stride] else src[s]
                acc += next - prev
            }
        }
    }

    private fun blurRect(a: FloatArray, ao: Int, tmp: FloatArray, to: Int, pitch: Int, w: Int, h: Int, r: Int) {
        if (r == 0 || w <= 0 || h <= 0) return
        repeat(2) {
            boxPass(a, ao, tmp, to, h, w, pitch, 1, r)
            boxPass(tmp, to, a, ao, w, h, 1, pitch, r)
        }
    }

    /** Chroma averaged over 2 x 2 blocks, blurred with radius [r] there, interpolated back. */
    private fun chromaHalf(cb: FloatArray, cr: FloatArray, hb: FloatArray, hr: FloatArray, tmp: FloatArray, w: Int, h: Int, r: Int) {
        val hw = (w + 1) / 2
        val hh = (h + 1) / 2
        for (y in 0 until hh) {
            val y0 = 2 * y; val y1 = minOf(2 * y + 1, h - 1)
            for (x in 0 until hw) {
                val x0 = 2 * x; val x1 = minOf(2 * x + 1, w - 1)
                val a = y0 * w + x0; val b = y0 * w + x1; val c = y1 * w + x0; val d = y1 * w + x1
                hb[y * hw + x] = (cb[a] + cb[b] + cb[c] + cb[d]) * 0.25f
                hr[y * hw + x] = (cr[a] + cr[b] + cr[c] + cr[d]) * 0.25f
            }
        }
        blurRect(hb, 0, tmp, 0, hw, hw, hh, r)
        blurRect(hr, 0, tmp, 0, hw, hw, hh, r)
        for (y in 0 until h) {
            val fy = maxOf(0f, (y - 0.5f) * 0.5f)
            var iy = fy.toInt(); var jy: Int; var ty: Float
            if (iy + 1 < hh) { jy = iy + 1; ty = fy - iy } else { iy = hh - 1; jy = hh - 1; ty = 0f }
            for (x in 0 until w) {
                val fx = maxOf(0f, (x - 0.5f) * 0.5f)
                var ix = fx.toInt(); var jx: Int; var tx: Float
                if (ix + 1 < hw) { jx = ix + 1; tx = fx - ix } else { ix = hw - 1; jx = hw - 1; tx = 0f }
                val i00 = iy * hw + ix; val i01 = iy * hw + jx; val i10 = jy * hw + ix; val i11 = jy * hw + jx
                val bt = hb[i00] + (hb[i01] - hb[i00]) * tx
                val bb = hb[i10] + (hb[i11] - hb[i10]) * tx
                cb[y * w + x] = bt + (bb - bt) * ty
                val rt = hr[i00] + (hr[i01] - hr[i00]) * tx
                val rb = hr[i10] + (hr[i11] - hr[i10]) * tx
                cr[y * w + x] = rt + (rb - rt) * ty
            }
        }
    }

    private fun mix(s: Int): Int {
        var h = s * -0x61c88647 xor -0x7a143595
        h = h xor (h ushr 13)
        h *= -0x3d4d51cb
        return h xor (h ushr 16)
    }

    /**
     * The photo as [key]'s camera made it at [iso] (100..1600), mixed with the original by
     * [strength]; a new bitmap. Run off the main thread (a 12 MP photo takes a few seconds).
     */
    fun apply(context: Context, src: Bitmap, key: String, iso: Int, strength: Float, seed: Int): Bitmap {
        val cam = camera(key) ?: return src
        // the native port (cpp/digicam.cpp, optimised in every build) does the work; this Kotlin
        // one below is its reference and the fallback
        runCatching {
            val input = if (src.config == Bitmap.Config.ARGB_8888) src else src.copy(Bitmap.Config.ARGB_8888, false)
            val out = Bitmap.createBitmap(src.width, src.height, Bitmap.Config.ARGB_8888)
            val raw = context.assets.open("luts/digicam/$key.lut").use { it.readBytes() }
            val params = FloatArray(32).also { p ->
                p[0] = cam.channels.toFloat()
                for (r in 0..3) for (c in 0..2) p[1 + r * 3 + c] = cam.sceneToRaw[r][c]
                for (r in 0..2) for (c in 0..3) p[13 + r * 4 + c] = cam.rawToScene[r][c]
                p[25] = cam.megapixels; p[26] = cam.fullWell; p[27] = cam.sharpen; p[28] = cam.sharpenRadius
                p[29] = cam.nr; p[30] = cam.bloom; p[31] = cam.fringe
            }
            val ok = FilmNative.digicam(input, out, raw, params, iso, strength, seed)
            if (input !== src) input.recycle()
            if (ok) return out
            out.recycle()
        }
        return applyKotlin(context, src, cam, iso, strength, seed)
    }

    private fun applyKotlin(context: Context, src: Bitmap, cam: Camera, iso: Int, strength: Float, seed: Int): Bitmap {
        val key = cam.key
        val W = src.width
        val H = src.height
        val isoGain = (iso / 100f).coerceIn(1f, 16f)
        val nrAmt = cam.nr * sqrt(isoGain)
        val sharpenAmt = cam.sharpen
        val bloomAmt = cam.bloom
        val fringeAmt = cam.fringe
        val str = strength.coerceIn(0f, 1f)
        val f = (sqrt(W.toFloat() * H / (cam.megapixels * 1e6f)) + 0.5f).toInt().coerceIn(1, 4)
        val cw = (W + f - 1) / f
        val ch = (H + f - 1) / f
        val lut = lut(context, key)
        val noise = noiseTile()
        val ox = Math.floorMod(mix(seed), NT)
        val oy = Math.floorMod(mix(seed xor 0x5bd1e995), NT)
        val invFw = isoGain / cam.fullWell
        val readVar = run {
            val pre = READ_NOISE * 0.25f
            val post = READ_NOISE / isoGain
            val sigma = sqrt(pre * pre + post * post) * isoGain / cam.fullWell
            sigma * sigma
        }
        val amp = 1f / 32f
        val s = cam.sceneToRaw
        val a = cam.rawToScene
        val k4 = cam.channels == 4
        // the overlap in camera rows: the emulator's 16 document pixels, even
        val ov = (ceil(16f / f).toInt() + 1) / 2 * 2
        val out = Bitmap.createBitmap(W, H, Bitmap.Config.ARGB_8888)
        // bands in parallel (each its own planes; they write disjoint rows)
        val threads = minOf(4, Runtime.getRuntime().availableProcessors()).coerceAtLeast(1)
        val pool = java.util.concurrent.Executors.newFixedThreadPool(threads)
        val starts = (0 until ch step BAND).toList()
        val failure = java.util.concurrent.atomic.AtomicReference<Throwable?>(null)
        val jobs = starts.map { start -> pool.submit {
          runCatching {
            val rgb = FloatArray(3)
            val c0 = start
            val c1 = minOf(ch, c0 + BAND)
            val a0 = maxOf(0, c0 - ov)
            val a1 = minOf(ch, c1 + ov)
            val pw = cw
            val ph = a1 - a0
            val area = pw * ph
            // ---- 0: camera pixels, the mean of encoded values per f x f block (decoded once)
            val docY0 = a0 * f
            val docY1 = minOf(H, a1 * f)
            val px = IntArray(W * (docY1 - docY0))
            src.getPixels(px, 0, W, 0, docY0, W, docY1 - docY0)
            val inR = FloatArray(area); val inG = FloatArray(area); val inB = FloatArray(area); val inC = FloatArray(area)
            val cnt = FloatArray(area)
            for (dy in 0 until docY1 - docY0) {
                val row = (dy / f) * pw
                for (dx in 0 until W) {
                    val c = px[dy * W + dx]
                    val l = row + dx / f
                    val rr = (c shr 16) and 0xff; val gg = (c shr 8) and 0xff; val bb2 = c and 0xff
                    inR[l] += rr / 255f; inG[l] += gg / 255f; inB[l] += bb2 / 255f
                    if (rr >= 255 || gg >= 255 || bb2 >= 255) inC[l] += 1f
                    cnt[l] += 1f
                }
            }
            for (i in 0 until area) {
                val inv = 1f / maxOf(cnt[i], 1f)
                inR[i] = decode(inR[i] * inv); inG[i] = decode(inG[i] * inv); inB[i] = decode(inB[i] * inv); inC[i] *= inv
            }
            // ---- 1-2: noise, the camera, Y'CbCr; the blown-highlight map
            val py = FloatArray(area); val pcb = FloatArray(area); val pcr = FloatArray(area); val blown = FloatArray(area)
            val cols = BooleanArray(pw)
            var bx0 = Int.MAX_VALUE; var bx1 = -1; var by0 = Int.MAX_VALUE; var by1 = -1
            for (y in 0 until ph) {
                val nrow = ((a0 + y + oy) and (NT - 1)) * NT * 4
                for (x in 0 until pw) {
                    val i = y * pw + x
                    var r = inR[i]; var g = inG[i]; var b = inB[i]
                    val r0 = s[0][0] * r + s[0][1] * g + s[0][2] * b
                    val r1 = s[1][0] * r + s[1][1] * g + s[1][2] * b
                    val r2 = s[2][0] * r + s[2][1] * g + s[2][2] * b
                    val r3 = if (k4) s[3][0] * r + s[3][1] * g + s[3][2] * b else 0f
                    var top = maxOf(r0, maxOf(r1, r2))
                    if (k4 && r3 > top) top = r3
                    // a channel at the top of the 8-bit photo was clipped already: one stop over
                    if (inC[i] >= 0.5f && 2f > top) top = 2f
                    if (top > 1f) {
                        blown[i] = log2(top); cols[x] = true
                        if (x < bx0) bx0 = x; if (x > bx1) bx1 = x; if (y < by0) by0 = y; by1 = y
                    }
                    val q = nrow + ((x + ox) and (NT - 1)) * 4
                    val d0 = noise[q] * sqrt(r0.coerceIn(0f, 1f) * invFw + readVar) * amp
                    val d1 = noise[q + 1] * sqrt(r1.coerceIn(0f, 1f) * invFw + readVar) * amp
                    val d2 = noise[q + 2] * sqrt(r2.coerceIn(0f, 1f) * invFw + readVar) * amp
                    val d3 = if (k4) noise[q + 3] * sqrt(r3.coerceIn(0f, 1f) * invFw + readVar) * amp else 0f
                    r += a[0][0] * d0 + a[0][1] * d1 + a[0][2] * d2 + a[0][3] * d3
                    g += a[1][0] * d0 + a[1][1] * d1 + a[1][2] * d2 + a[1][3] * d3
                    b += a[2][0] * d0 + a[2][1] * d1 + a[2][2] * d2 + a[2][3] * d3
                    render(lut, maxOf(r, 0f), maxOf(g, 0f), maxOf(b, 0f), rgb)
                    val yy = 0.299f * rgb[0] + 0.587f * rgb[1] + 0.114f * rgb[2]
                    py[i] = yy; pcb[i] = rgb[2] - yy; pcr[i] = rgb[0] - yy
                }
            }
            val s1 = FloatArray(area + 2 * (pw + ph) + 8)
            val s2 = FloatArray(area + 2 * (pw + ph) + 8)
            if (by1 >= 0) {
                // ---- 3: blooming along the columns with a blown pixel
                if (bloomAmt > 0f) {
                    val reachDoc = minOf(1.5f + 1.5f * bloomAmt, 3.5f)
                    val reach = maxOf(reachDoc / f, 1f)
                    val gain = 0.16f * bloomAmt * reachDoc / reach
                    val keep = 1f - 1f / reach
                    for (x in bx0..bx1) {
                        if (!cols[x]) continue
                        var acc = 0f
                        for (y in 0 until ph) { acc = acc * keep + blown[y * pw + x]; s1[y * pw + x] = acc }
                        acc = 0f
                        for (y in ph - 1 downTo 0) {
                            val i = y * pw + x
                            val e = blown[i]
                            acc = acc * keep + e
                            val st = minOf((s1[i] + acc - e) * gain, 1f)
                            py[i] += (1f - py[i]) * st
                            pcb[i] *= 1f - st
                            pcr[i] *= 1f - st
                        }
                    }
                }
                // ---- 4: purple fringing round the blown pixels
                if (fringeAmt > 0f) {
                    val mg = 6
                    val xa = maxOf(0, bx0 - mg); val xb = minOf(pw - 1, bx1 + mg)
                    val ya = maxOf(0, by0 - mg); val yb = minOf(ph - 1, by1 + mg)
                    for (y in ya..yb) for (x in xa..xb) s1[y * pw + x] = minOf(blown[y * pw + x], 1f)
                    blurRect(s1, ya * pw + xa, s2, ya * pw + xa, pw, xb - xa + 1, yb - ya + 1, if (f == 1) 2 else 1)
                    val fr = 0.45f; val fg = -0.08f; val fb = 0.85f
                    val fy = 0.299f * fr + 0.587f * fg + 0.114f * fb
                    for (y in ya..yb) for (x in xa..xb) {
                        val i = y * pw + x
                        val edge = s1[i] - minOf(blown[i], 1f)
                        if (edge > 0f) {
                            val k = edge * fringeAmt * 0.9f
                            py[i] += k * fy; pcb[i] += k * (fb - fy); pcr[i] += k * (fr - fy)
                        }
                    }
                }
            }
            // ---- 5: noise reduction and sharpening
            var rc = minOf((nrAmt * 1.25f + 0.5f).toInt(), 6)
            if (f > 1) rc = (rc.toFloat() / f + 0.5f).toInt()
            rc = minOf(rc, maxOf(0, ov - 4) / 4)
            val half = ((pw + 1) / 2) * ((ph + 1) / 2)
            val hb = FloatArray(half); val hr = FloatArray(half); val ht = FloatArray(half)
            chromaHalf(pcb, pcr, hb, hr, ht, pw, ph, rc)
            val wl = ((nrAmt - 0.6f) * 0.35f).coerceIn(0f, 0.75f)
            if (wl > 0f || sharpenAmt > 0f) {
                val rs = maxOf(1, (cam.sharpenRadius + 0.5f).toInt())
                System.arraycopy(py, 0, s1, 0, area)
                blurRect(s1, 0, s2, 0, pw, pw, ph, rs)
                val k = sharpenAmt * 1.6f
                for (i in 0 until area) {
                    val bl = s1[i]
                    val y = py[i] + (bl - py[i]) * wl
                    var d = y - bl
                    d = if (d > 0.004f) d - 0.004f else if (d < -0.004f) d + 0.004f else 0f
                    py[i] = y + d * k
                }
            }
            // ---- 6: back to the photo's pixels for this band's own rows, mixed by strength
            for (i in 0 until area) {
                val yy = py[i]; val er = yy + pcr[i]; val eb = yy + pcb[i]
                val eg = (yy - 0.299f * er - 0.114f * eb) / 0.587f
                py[i] = er; pcb[i] = eg; pcr[i] = eb // now encoded R, G, B
            }
            val rowOut = IntArray(W)
            val coreY0 = c0 * f
            val coreY1 = minOf(H, c1 * f)
            val invF = 1f / f
            for (dy in coreY0 until coreY1) {
                val u = maxOf(0f, (dy + 0.5f) * invF - 0.5f - a0)
                var iy = u.toInt(); var jy: Int; var ty: Float
                if (iy + 1 < ph) { jy = iy + 1; ty = u - iy } else { iy = ph - 1; jy = ph - 1; ty = 0f }
                val srcRow = (dy - docY0) * W
                for (dx in 0 until W) {
                    val v = maxOf(0f, (dx + 0.5f) * invF - 0.5f)
                    var ix = v.toInt(); var jx: Int; var tx: Float
                    if (ix + 1 < pw) { jx = ix + 1; tx = v - ix } else { ix = pw - 1; jx = pw - 1; tx = 0f }
                    val i00 = iy * pw + ix; val i01 = iy * pw + jx; val i10 = jy * pw + ix; val i11 = jy * pw + jx
                    var t = py[i00] + (py[i01] - py[i00]) * tx; var bt = py[i10] + (py[i11] - py[i10]) * tx
                    var er = t + (bt - t) * ty
                    t = pcb[i00] + (pcb[i01] - pcb[i00]) * tx; bt = pcb[i10] + (pcb[i11] - pcb[i10]) * tx
                    var eg = t + (bt - t) * ty
                    t = pcr[i00] + (pcr[i01] - pcr[i00]) * tx; bt = pcr[i10] + (pcr[i11] - pcr[i10]) * tx
                    var eb = t + (bt - t) * ty
                    val o = px[srcRow + dx]
                    if (str < 1f) {
                        er = encode(dec8[(o shr 16) and 0xff] + (decode(er) - dec8[(o shr 16) and 0xff]) * str)
                        eg = encode(dec8[(o shr 8) and 0xff] + (decode(eg) - dec8[(o shr 8) and 0xff]) * str)
                        eb = encode(dec8[o and 0xff] + (decode(eb) - dec8[o and 0xff]) * str)
                    }
                    rowOut[dx] = (0xff shl 24) or
                        ((er.coerceIn(0f, 1f) * 255f + 0.5f).toInt() shl 16) or
                        ((eg.coerceIn(0f, 1f) * 255f + 0.5f).toInt() shl 8) or
                        (eb.coerceIn(0f, 1f) * 255f + 0.5f).toInt()
                }
                synchronized(out) { out.setPixels(rowOut, 0, W, 0, dy, W, 1) }
            }
          }.onFailure { failure.compareAndSet(null, it) }
        } }
        jobs.forEach { it.get() }
        pool.shutdown()
        failure.get()?.let { throw it }
        return out
    }
}
