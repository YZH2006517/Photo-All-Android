/**
 * The look of 2000s CCD compact cameras on a developed photo: a port of the filter in
 * Marcs Digicam Emulator by Marc Gronenberg (MIT; github.com/marc-gronenberg/marcs-digicam-emulator,
 * plugin/src/lib.rs), its stages and constants unchanged:
 *
 * 0. the photo at about the camera's megapixels (f x f blocks, f from the two sizes, 1-4);
 * 1. sensor noise in the raw channels (shot noise from the pixel's full well, read noise,
 *    both growing with ISO), carried into the scene through the camera's white balance and
 *    colour matrix, so the strong matrices of the CMYG sensors make coloured noise;
 * 2. the camera's 37^3 LUT (sensor, clip at full well, white balance, matrix, tone curve,
 *    the maker's style), kept as Y'CbCr;
 * 3. CCD blooming: charge from clipped pixels spilling up and down the column;
 * 4. purple fringing on the dark side of clipped highlights;
 * 5. the camera's noise reduction (chroma at half resolution and blurred, as its 4:2:0
 *    JPEG stored it; luma softened at high ISO) and its sharpening (unsharp mask, halos);
 * 6. back to the photo's size, mixed with it by strength in linear light.
 *
 * The photo is worked in bands of camera rows with an overlap, so a large one needs little
 * memory and the spatial stages meet without seams; the noise is fixed to the pixel.
 */
object Digicam {
    private const val N = 37
    private const val STOPS_LO = -8f
    private const val STOPS_HI = 5f
    private val LOG2_018 = (ln(0.18) / ln(2.0)).toFloat()
    private const val READ_NOISE = 10f
    private const val NT = 1024
    private const val DR = 3
    private const val DG = N * 3
    private const val DB = N * N * 3
    private const val BAND = 192 // camera rows per band (even: chroma's 2 x 2 blocks stay on the grid)

    class Camera(
        val key: String, val channels: Int,
        /** linear scene (grey 0.18) -> raw signal as a fraction of full well, 4 x 3 */
        val sceneToRaw: Array<FloatArray>,
        /** raw noise -> linear scene, through white balance and colour matrix, 3 x 4 */
        val rawToScene: Array<FloatArray>,
        val megapixels: Float, val fullWell: Float, val sharpen: Float, val sharpenRadius: Float,
        val nr: Float, val bloom: Float, val fringe: Float,
    )

    private fun m(vararg rows: FloatArray) = arrayOf(*rows)
    private fun r(vararg v: Float) = v

